// Rebuild the shipped browser assets from the exact npm lockfile.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = [
	['@google/model-viewer/dist/model-viewer.min.js', 'model-viewer.min.js'],
	['@google/model-viewer/LICENSE', 'LICENSE-model-viewer.txt'],
	['three/LICENSE', 'LICENSE-three.txt'],
	['lit/LICENSE', 'LICENSE-lit.txt'],
	['@monogrid/gainmap-js/LICENSE', 'LICENSE-gainmap.txt'],
	['three/examples/jsm/libs/draco/gltf/draco_decoder.js', 'draco/draco_decoder.js'],
	['three/examples/jsm/libs/draco/gltf/draco_decoder.wasm', 'draco/draco_decoder.wasm'],
	['three/examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js', 'draco/draco_wasm_wrapper.js'],
	['three/examples/jsm/libs/basis/basis_transcoder.js', 'basis/basis_transcoder.js'],
	['three/examples/jsm/libs/basis/basis_transcoder.wasm', 'basis/basis_transcoder.wasm'],
	['three/examples/jsm/libs/meshopt_decoder.module.js', 'meshopt_decoder.js'],
];
const hashes = {};
for (const [source, target] of assets) {
	const destination = resolve(root, 'html/vendor/model-viewer', target);
	await mkdir(resolve(destination, '..'), { recursive: true });
	await copyFile(resolve(root, 'node_modules', source), destination);
	if (target === 'meshopt_decoder.js') {
		// model-viewer loads this decoder as a classic script, not an ES module.
		const module = await readFile(destination, 'utf8');
		const exported = 'export { MeshoptDecoder };';
		if (!module.trimEnd().endsWith(exported)) throw new Error('Unexpected Meshopt export; review the vendor update');
		await writeFile(destination, module.replace(exported, '// Classic-script build generated by vendor-model-viewer.mjs.'));
	}
	hashes[target] = createHash('sha256').update(await readFile(destination)).digest('hex');
}
await writeFile(resolve(root, 'html/vendor/model-viewer/checksums.json'), JSON.stringify(hashes, null, 2) + '\n');
console.log(`Vendored ${assets.length} model-viewer assets from package-lock.json`);
